@app.route("/trips/<int:trip_id>")
@login_required
def trip_detail(trip_id: int):
    """
    Page 6: Trip details dashboard with budget summary and daily itinerary.
    Strict user-scoping: Queries trip matching both trip_id and owner_id.
    """
    user_id = session["user_id"]

    # Scoped query ensuring User B cannot read User A's private trip
    stmt = db.select(Trip).where(Trip.id == trip_id, Trip.owner_id == user_id)
    trip = db.session.execute(stmt).scalar_one_or_none()

    if not trip:
        abort(404)

    # Group activities by date in chronological order
    itinerary_by_date: Dict[datetime.date, List[Activity]] = {}
    for act in trip.activities:
        if act.activity_date not in itinerary_by_date:
            itinerary_by_date[act.activity_date] = []
        itinerary_by_date[act.activity_date].append(act)

    sorted_itinerary = sorted(itinerary_by_date.items(), key=lambda x: x[0])

    return render_template(
        "trip_detail.html",
        trip=trip,
        itinerary=sorted_itinerary,
        total_activities_count=len(trip.activities),
    )



class User(db.Model):
    """
    User account model.
    Stores authentication credentials and manages one-to-many relationship with Trips.
    """
    __tablename__ = "users"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Unique username for identification and login
    username: Mapped[str] = mapped_column(String(80), unique=True, nullable=False, index=True)

    # Secure Werkzeug password hash
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)

    # Registration timestamp
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime, default=datetime.datetime.utcnow, nullable=False
    )

    # Relationship: One user owns multiple trips
    # When a user is deleted, all their associated trips are automatically removed
    trips: Mapped[List["Trip"]] = relationship(
        "Trip", back_populates="owner", cascade="all, delete-orphan", lazy="select"
    )

    def set_password(self, password: str) -> None:
        """Hash and store a user password securely using Werkzeug."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        """Verify candidate password against the stored password hash."""
        return check_password_hash(self.password_hash, password)

    def __repr__(self) -> str:
        return f"<User {self.username}>"


class Trip(db.Model):
    """
    Trip model representing a scheduled trip with destination, dates, and budget.
    """
    __tablename__ = "trips"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Foreign key referencing users.id
    owner_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Target destination title (e.g. 'Paris, France')
    destination: Mapped[str] = mapped_column(String(120), nullable=False)

    # Trip scheduled start and end dates
    start_date: Mapped[datetime.date] = mapped_column(Date, nullable=False)
    end_date: Mapped[datetime.date] = mapped_column(Date, nullable=False)

    # Total financial budget with fixed precision decimal
    budget: Mapped[Decimal] = mapped_column(
        Numeric(10, 2), nullable=False, default=Decimal("0.00")
    )

    # Audit timestamps
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime, default=datetime.datetime.utcnow, nullable=False
    )
    updated_at: Mapped[datetime.datetime] = mapped_column(
        DateTime,
        default=datetime.datetime.utcnow,
        onupdate=datetime.datetime.utcnow,
        nullable=False,
    )

    # Relationships
    owner: Mapped["User"] = relationship("User", back_populates="trips")

    # Activities ordered chronologically by date and time
    activities: Mapped[List["Activity"]] = relationship(
        "Activity",
        back_populates="trip",
        cascade="all, delete-orphan",
        lazy="select",
        order_by="Activity.activity_date, Activity.activity_time",
    )

    # Table constraints enforcing business rules at the database level
    __table_args__ = (
        CheckConstraint("end_date >= start_date", name="chk_trip_dates"),
        CheckConstraint("budget >= 0", name="chk_trip_budget"),
    )

    @property
    def duration_days(self) -> int:
        """Total duration in days inclusive of start and end date."""
        if self.start_date and self.end_date:
            return (self.end_date - self.start_date).days + 1
        return 0

    @property
    def total_cost(self) -> Decimal:
        """Sum of all saved activity costs belonging to this trip."""
        total = Decimal("0.00")
        for activity in self.activities:
            if activity.cost is not None:
                total += Decimal(str(activity.cost))
        return total

    @property
    def budget_difference(self) -> Decimal:
        """Compute difference: trip budget minus total estimated activity costs."""
        trip_budget = Decimal(str(self.budget)) if self.budget is not None else Decimal("0.00")
        return trip_budget - self.total_cost

    @property
    def budget_status(self) -> str:
        """Textual display of current budget state."""
        diff = self.budget_difference
        if diff > 0:
            return "Budget Remaining"
        elif diff == 0:
            return "Budget Fully Used"
        else:
            return "Budget Exceeded"

    @property
    def budget_status_class(self) -> str:
        """CSS class corresponding to budget status."""
        diff = self.budget_difference
        if diff > 0:
            return "status-remaining"
        elif diff == 0:
            return "status-used"
        else:
            return "status-exceeded"

    @property
    def utilization_percentage(self) -> float:
        """Calculate percentage of budget utilized."""
        trip_budget = Decimal(str(self.budget)) if self.budget is not None else Decimal("0.00")
        if trip_budget <= 0:
            return 100.0 if self.total_cost > 0 else 0.0
        pct = (self.total_cost / trip_budget) * 100
        return round(float(pct), 1)

    def __repr__(self) -> str:
        return f"<Trip {self.destination} ({self.start_date} to {self.end_date})>"


class Activity(db.Model):
    """
    Activity model representing an itinerary event belonging to a trip.
    """
    __tablename__ = "activities"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Foreign key referencing trips.id
    trip_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("trips.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Activity name
    name: Mapped[str] = mapped_column(String(150), nullable=False)

    # Scheduled date (must fall between trip start and end date)
    activity_date: Mapped[datetime.date] = mapped_column(Date, nullable=False, index=True)

    # Scheduled time of the activity
    activity_time: Mapped[datetime.time] = mapped_column(Time, nullable=False)

    # Category (Sightseeing, Food, Adventure, etc.)
    category: Mapped[str] = mapped_column(String(50), nullable=False)

    # Place or venue address
    place: Mapped[str] = mapped_column(String(150), nullable=False)

    # Estimated monetary cost
    cost: Mapped[Decimal] = mapped_column(
        Numeric(10, 2), nullable=False, default=Decimal("0.00")
    )

    # Timestamps
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime, default=datetime.datetime.utcnow, nullable=False
    )
    updated_at: Mapped[datetime.datetime] = mapped_column(
        DateTime,
        default=datetime.datetime.utcnow,
        onupdate=datetime.datetime.utcnow,
        nullable=False,
    )

    # Relationship back to parent Trip
    trip: Mapped["Trip"] = relationship("Trip", back_populates="activities")

    __table_args__ = (
        CheckConstraint("cost >= 0", name="chk_activity_cost"),
    )

    def __repr__(self) -> str:
        return f"<Activity {self.name} on {self.activity_date}>"



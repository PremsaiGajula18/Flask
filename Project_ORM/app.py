    """
    Page 5: Edit an existing trip.
    Validates date bounds against existing activities before applying changes.
    Uses ORM session change tracking and db.session.commit().
    """
    user_id = session["user_id"]
    errors: Dict[str, str] = {}

    stmt = db.select(Trip).where(Trip.id == trip_id, Trip.owner_id == user_id)
    trip = db.session.execute(stmt).scalar_one_or_none()

    if not trip:
        abort(404)

    if request.method == "GET":
        form_data = {
            "destination": trip.destination,
            "start_date": trip.start_date.strftime("%Y-%m-%d"),
            "end_date": trip.end_date.strftime("%Y-%m-%d"),
            "budget": str(trip.budget),
        }
    else:
        destination = request.form.get("destination", "").strip()
        start_date_str = request.form.get("start_date", "").strip()
        end_date_str = request.form.get("end_date", "").strip()
        budget_str = request.form.get("budget", "").strip()

        form_data = {
            "destination": destination,
            "start_date": start_date_str,
            "end_date": end_date_str,
            "budget": budget_str,
        }

        if not destination:
            errors["destination"] = "Destination is required."

        new_start_date = None
        if not start_date_str:
            errors["start_date"] = "Start date is required."
        else:
            try:
                new_start_date = datetime.datetime.strptime(start_date_str, "%Y-%m-%d").date()
            except ValueError:
                errors["start_date"] = "Invalid start date format."

        new_end_date = None
        if not end_date_str:
            errors["end_date"] = "End date is required."
        else:
            try:
                new_end_date = datetime.datetime.strptime(end_date_str, "%Y-%m-%d").date()
            except ValueError:
                errors["end_date"] = "Invalid end date format."

        if new_start_date and new_end_date and new_end_date < new_start_date:
            errors["end_date"] = "End date cannot be earlier than start date."

        new_budget = None
        if not budget_str:
            errors["budget"] = "Total budget is required."
        else:
            try:
                new_budget = Decimal(budget_str)
                if new_budget < 0:
                    errors["budget"] = "Budget cannot be negative."
            except (InvalidOperation, ValueError):
                errors["budget"] = "Budget must be a valid numeric value."

        # Business Rule 5: Prevent date changes that leave existing activities outside updated period
        if new_start_date and new_end_date and not errors.get("start_date") and not errors.get("end_date"):
            conflict_stmt = db.select(Activity).where(
                Activity.trip_id == trip.id,
                or_(
                    Activity.activity_date < new_start_date,
                    Activity.activity_date > new_end_date,
                ),
            )
            conflicting_activities = db.session.execute(conflict_stmt).scalars().all()

            if conflicting_activities:
                conflict_details = [
                    f'"{a.name}" on {a.activity_date.strftime("%Y-%m-%d")}'
                    for a in conflicting_activities
                ]
                errors["general"] = (
                    f"Cannot change trip dates. The following {len(conflicting_activities)} "
                    f"activity(ies) would fall outside the new date range ({new_start_date} to {new_end_date}): "
                    f"{', '.join(conflict_details)}. Please update or delete them first."
                )

        if not errors:
            # Modify attributes on loaded ORM entity
            trip.destination = destination
            trip.start_date = new_start_date
            trip.end_date = new_end_date
            trip.budget = new_budget

            # Commit tracked changes
            db.session.commit()
            flash("Trip updated successfully!", "success")
            return redirect(url_for("trip_detail", trip_id=trip.id))

    return render_template("trip_form.html", is_edit=True, trip=trip, errors=errors, form_data=form_data)



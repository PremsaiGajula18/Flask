@app.route("/register", methods=["GET", "POST"])
def register():
    """
    Page 2: Register a new user account.
    Uses SQLAlchemy ORM select query to check uniqueness, then db.session.add() and db.session.commit().
    """
    if current_user.is_authenticated:
        return redirect(url_for("my_trips"))

    errors: Dict[str, str] = {}
    form_data: Dict[str, str] = {}

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        confirm_password = request.form.get("confirm_password", "")
        form_data["username"] = username

        # Username validation
        if not username:
            errors["username"] = "Username is required."
        elif len(username) < 3 or len(username) > 50:
            errors["username"] = "Username must be between 3 and 50 characters."
        else:
            # Check duplicate username using SQLAlchemy ORM
            existing_user = db.session.execute(
                db.select(User).where(User.username == username)
            ).scalar_one_or_none()
            if existing_user:
                errors["username"] = "That username is already taken. Please choose another."

        # Password validation
        if not password:
            errors["password"] = "Password is required."
        elif len(password) < 6:
            errors["password"] = "Password must be at least 6 characters long."

        # Password confirmation match
        if not confirm_password:
            errors["confirm_password"] = "Please confirm your password."
        elif password != confirm_password:
            errors["confirm_password"] = "Passwords do not match."

        # If all fields are valid, create user through ORM session
        if not errors:
            new_user = User(username=username)
            new_user.set_password(password)

            db.session.add(new_user)
            db.session.commit()

            flash("Registration successful! Please log in.", "success")
            return redirect(url_for("login"))

    return render_template("register.html", errors=errors, form_data=form_data)


@app.route("/login", methods=["GET", "POST"])
def login():
    """
    Page 3: User login route.
    Uses ORM db.select to query the user, provides specific error feedback for
    non-existent usernames vs incorrect passwords, and initializes session.
    """
    if current_user.is_authenticated:
        return redirect(url_for("my_trips"))

    errors: Dict[str, str] = {}
    form_data: Dict[str, str] = {}

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        form_data["username"] = username

        if not username:
            errors["username"] = "Username is required."
        if not password:
            errors["password"] = "Password is required."

        if not errors:
            # Look up user via ORM
            user = db.session.execute(
                db.select(User).where(User.username == username)
            ).scalar_one_or_none()

            if not user:
                errors["username"] = "User does not exist. Please check your username."
            elif not user.check_password(password):
                errors["password"] = "Incorrect password. Please try again."
            else:
                # Successfully authenticated
                session.clear()
                session["user_id"] = user.id
                session["username"] = user.username
                session["csrf_token"] = secrets.token_hex(24)

                flash(f"Welcome back, {user.username}!", "success")
                next_page = request.args.get("next")
                if next_page and next_page.startswith("/"):
                    return redirect(next_page)
                return redirect(url_for("my_trips"))

    return render_template("login.html", errors=errors, form_data=form_data)



def generate_csrf_token() -> str:
    """Generate or retrieve a cryptographically secure per-session CSRF token."""
    if "csrf_token" not in session:
        session["csrf_token"] = secrets.token_hex(24)
    return session["csrf_token"]


class CurrentUserProxy:
    """
    Template proxy mimicking Flask-Login's current_user object.
    Provides current_user.is_authenticated, current_user.id, and current_user.username
    directly from the active Flask session.
    """
    @property
    def is_authenticated(self) -> bool:
        return "user_id" in session

    @property
    def id(self) -> Optional[int]:
        return session.get("user_id")

    @property
    def username(self) -> Optional[str]:
        return session.get("username")


current_user = CurrentUserProxy()


@app.context_processor
def inject_globals() -> Dict[str, Any]:
    """Inject CSRF token generator, current_user, year, and categories into all templates."""
    return {
        "csrf_token": generate_csrf_token,
        "current_user": current_user,
        "now_year": datetime.datetime.now().year,
        "categories": ACTIVITY_CATEGORIES,
    }


@app.before_request
def verify_csrf_token() -> Optional[Any]:
    """Verify CSRF tokens on all state-changing HTTP POST requests."""
    if request.method == "POST":
        submitted_token = request.form.get("csrf_token")
        expected_token = session.get("csrf_token")

        if not submitted_token or submitted_token != expected_token:
            flash("Security check failed (invalid or missing CSRF token). Please try again.", "danger")
            return redirect(request.referrer or url_for("home"))
    return None


def login_required(view: Callable) -> Callable:
    """Decorator requiring active authenticated session before accessing protected views."""
    @functools.wraps(view)
    def wrapped_view(**kwargs):
        if session.get("user_id") is None:
            flash("Please log in to access this page.", "warning")
            return redirect(url_for("login", next=request.url))
        return view(**kwargs)

    return wrapped_view


